let lang='';
try { lang=localStorage.getItem('human-experiment-language') || ''; } catch {}
if (!GOAL_TEXT[lang]) {
  const browserLanguages=(navigator.languages&&navigator.languages.length?navigator.languages:[navigator.language||'en']);
  lang=browserLanguages.map(value=>String(value).toLowerCase().split('-')[0]).find(value=>GOAL_TEXT[value])||'en';
  try { localStorage.setItem('human-experiment-language',lang); } catch {}
}
const languageSelect=document.querySelector('#page-language');
function applyGoalLanguage(){
  const t=GOAL_TEXT[lang];
  document.documentElement.lang=lang;
  document.documentElement.dir=lang==='ar'?'rtl':'ltr';
  document.querySelectorAll('[data-t]').forEach(el=>{
    const value=t[el.dataset.t];
    if(value) el.textContent=value;
  });
  if(languageSelect) languageSelect.value=lang;
  document.title=`${t.titleTag} - THE HUMAN EXPERIMENT`;
}
languageSelect?.addEventListener('change',()=>{
  lang=GOAL_TEXT[languageSelect.value]?languageSelect.value:'en';
  try { localStorage.setItem('human-experiment-language',lang); } catch {}
  applyGoalLanguage();
});
applyGoalLanguage();
